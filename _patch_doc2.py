import io
p='游戏策划案_V0.9_审核标记版.md'
s=io.open(p,encoding='utf-8').read()
fails=[]

def rep(old,new,tag=''):
    global s
    if old in s:
        s=s.replace(old,new,1)
    else:
        fails.append(tag)

# 4.2 技能使用方式
rep('**[A改]** 技能使用方式：**滚轮选中后右键触发、不设独立快捷键 = 全游戏通用技能使用方式**（非防守方专属）。',
    '**[A改]** 技能使用方式：**技能槽快捷键直接触发 = 全游戏通用技能使用方式**（U I O L H 对应槽位 1~5，非防守方专属；2026-09-06 拍板）。','4.2')

# 7.1 获得分支 滚轮表述
rep('| 未持有且槽未满 → 入槽（滚轮可选中）','| 未持有且槽未满 → 入槽（技能槽快捷键可触发）')

# ch12 滚轮行删除
rep('**[A]** 鼠标滚轮在技能列表（局内获得技能 + 角色固有主动技能/大招）中循环选择当前技能。\n','')

# 4.2 机动性
rep('**[A改]** 防守方机动性强于进攻方（基础移速更高，可手动触发加速/位移）。',
    '**[A改]** 防守方机动性强于进攻方（移速属性已删除，机动性差异改为动画/位移技能表现，**载体待重新设计**）。','4.2机动')

io.open(p,'w',encoding='utf-8',newline='\n').write(s)
print('fails:',fails if fails else 'none')
